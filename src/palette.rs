/// Thermal visualization palettes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Palette {
    #[default]
    Iron,
    Rainbow,
    WhiteHot,
    BlackHot,
    RedHot,
}

impl Palette {
    /// Applies the palette to an 8-bit intensity value (0 to 255), returning RGB.
    #[inline]
    pub fn map_color(&self, val: u8) -> [u8; 3] {
        match self {
            Self::Iron => IRON_PALETTE[val as usize],
            Self::WhiteHot => [val, val, val],
            Self::BlackHot => [255 - val, 255 - val, 255 - val],
            Self::RedHot => {
                if val < 128 {
                    [val * 2, 0, 0]
                } else {
                    [255, (val - 128) * 2, (val - 128) * 2]
                }
            }
            Self::Rainbow => {
                // Classic HSV-based rainbow mapping
                let h = (255 - val) as f32 / 255.0 * 240.0; // 240 (blue) down to 0 (red)
                hsv_to_rgb(h, 1.0, 1.0)
            }
        }
    }
}

fn hsv_to_rgb(h: f32, s: f32, v: f32) -> [u8; 3] {
    let c = v * s;
    let x = c * (1.0 - (((h / 60.0) % 2.0) - 1.0).abs());
    let m = v - c;

    let (r, g, b) = match (h as u32) / 60 {
        0 => (c, x, 0.0),
        1 => (x, c, 0.0),
        2 => (0.0, c, x),
        3 => (0.0, x, c),
        4 => (x, 0.0, c),
        _ => (c, 0.0, x),
    };

    [
        ((r + m) * 255.0).round() as u8,
        ((g + m) * 255.0).round() as u8,
        ((b + m) * 255.0).round() as u8,
    ]
}

